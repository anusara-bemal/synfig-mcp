"""
Data models for the Licensed Asset Pipeline, Provenance Manifest, and License Policies (Phase A5).
"""

from __future__ import annotations

import datetime

from pydantic import BaseModel, Field


class LicensePolicy(BaseModel):
    """
    Configurable license policy for external assets.
    Default configuration is strict: allows CC0/PDM, blocks ND/NC, flags BY/BY-SA.
    """

    allow_cc0: bool = Field(default=True, description="Allow CC0 / Public Domain Dedication.")
    allow_pdm: bool = Field(default=True, description="Allow Public Domain Mark.")
    allow_by: bool = Field(default=False, description="Allow CC BY (attribution required).")
    allow_by_sa: bool = Field(default=False, description="Allow CC BY-SA (Share-Alike required).")
    allow_commercial: bool = Field(
        default=True, description="Whether project requires commercial use."
    )
    block_nd: bool = Field(default=True, description="Block NoDerivatives (we transform assets).")
    block_nc: bool = Field(default=True, description="Block NonCommercial if commercial.")
    skip_mature: bool = Field(default=True, description="Reject mature/NSFW flagged content.")

    def evaluate_license(self, license_code: str, is_mature: bool = False) -> tuple[bool, str]:
        """
        Evaluate a license code against policy.
        Returns: (allowed: bool, reason: str).
        """
        if self.skip_mature and is_mature:
            return False, "Asset is flagged as mature content."

        code = license_code.lower().strip()

        if code in ("cc0", "pdm", "public-domain"):
            return True, "Permitted by policy (Public Domain / CC0)."

        if "nd" in code and self.block_nd:
            return (
                False,
                f"License '{code}' contains No-Derivatives (ND) clause; animation transformations prohibited.",
            )

        if "nc" in code and self.block_nc and self.allow_commercial:
            return (
                False,
                f"License '{code}' contains Non-Commercial (NC) restriction on a commercial project.",
            )

        if code == "by":
            if self.allow_by:
                return True, "Permitted by policy with attribution."
            return False, "License 'by' requires attribution and is disabled under strict policy."

        if code in ("by-sa", "sa"):
            if self.allow_by_sa:
                return True, "Permitted by policy with Share-Alike obligation."
            return (
                False,
                "License 'by-sa' requires Share-Alike and is disabled under strict policy.",
            )

        return False, f"License '{code}' is not permitted under active policy."


class AssetMetadata(BaseModel):
    """Provenance and licensing metadata captured at download time."""

    id: str = Field(description="Unique asset identifier (e.g. 'openverse_12345').")
    provider: str = Field(description="Source provider ('openverse', 'wikimedia', 'local').")
    title: str = Field(description="Asset title or filename.")
    creator: str = Field(default="Unknown", description="Original creator or copyright holder.")
    license_code: str = Field(description="Standard license identifier ('cc0', 'pdm', 'by', etc.).")
    license_url: str = Field(default="", description="Authoritative URL for license terms.")
    attribution_text: str = Field(default="", description="Ready-to-use attribution snippet.")
    download_url: str = Field(default="", description="Original HTTPS source download URL.")
    thumbnail_url: str | None = Field(default=None, description="Small preview URL.")
    filesize_bytes: int = Field(default=0, description="Size on disk in bytes.")
    sha256: str = Field(default="", description="Cryptographic SHA-256 hash.")
    local_path: str = Field(default="", description="Local file path within workspace.")
    retrieved_at: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.UTC).isoformat(),
        description="ISO 8601 UTC timestamp of download.",
    )
    rights_declaration: str = Field(
        default="", description="Declared rights basis ('own', 'licensed', 'cc0', 'public-domain')."
    )
    mature: bool = Field(default=False, description="Whether asset is flagged as mature.")


class AssetManifest(BaseModel):
    """Collection manifest of all imported assets stored at assets/manifest.json."""

    version: str = Field(default="1.0")
    assets: list[AssetMetadata] = Field(default_factory=list)

    def generate_attribution_md(self) -> str:
        """Auto-generate ATTRIBUTION.md for legal compliance and project distribution."""
        lines = [
            "# Project Asset Attribution & License Provenance",
            "",
            "> Auto-generated by Synfig MCP Asset Pipeline.",
            "> Every external asset used in this animation project is recorded with source and terms snapshot.",
            "",
            "| Asset Title | Creator | License | Provider | SHA-256 | Local File |",
            "|---|---|---|---|---|---|",
        ]
        for a in self.assets:
            c_link = f"[{a.creator}]({a.license_url})" if a.license_url else a.creator
            lines.append(
                f"| **{a.title}** | {c_link} | `{a.license_code.upper()}` | {a.provider} | `{a.sha256[:12]}...` | `{a.local_path}` |"
            )

        lines.extend(
            [
                "",
                "## Attribution Statements",
                "",
            ]
        )
        for a in self.assets:
            if a.attribution_text:
                lines.append(f"- **{a.title}**: {a.attribution_text}")

        return "\n".join(lines) + "\n"
